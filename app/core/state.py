from operator import add
from typing import Annotated, TypedDict

from app.models import CRAGEvaluation, ReflectionResult, RetrievedChunk


class GraphState(TypedDict, total=False):
    """
    Shared mutable state container passed between every node in the LangGraph
    StateGraph. Acts as the single source of truth for a query's full lifecycle —
    from the raw user question through intent routing, retrieval, SQL execution,
    guardrail checks, and final answer generation.

    Because LangGraph passes this dict by reference through each node, every field
    is optional (total=False). Nodes read only the fields they need and write only
    the fields they produce. Fields remain None/absent until the node responsible
    for populating them executes.

    Fields are grouped below by the pipeline stage that owns them.

    ── INPUT (set by the API layer before graph entry) ──────────────────────────

        question (str):
            Raw natural-language question from the user, after the 9-layer guardrail
            stack has sanitized, redacted, and injection-checked it.

        user_id (str):
            Authenticated user identifier from the JWT token. Used for per-user
            rate limiting, token budget enforcement, and cache key namespacing
            in Upstash Redis.

        flags (dict):
            Runtime feature toggles forwarded from the API request body, e.g.
            enable_rerank, enable_hyde, enable_crag, enable_self_reflective,
            search_mode. Controls which retrieval capabilities activate inside
            run_rag and retrieve_rag_for_hybrid nodes.

    ── INTENT ROUTING (set by route_intent node) ────────────────────────────────

        intent (str):
            One of 'rag', 'sql', or 'hybrid'. Set by classify_intent() upstream
            and read by route_intent to branch the LangGraph conditional edges.
            Also read again at request_sql_approval to determine whether to
            continue to run_sql or run_hybrid after operator approval.

    ── SQL PIPELINE (set by generate_sql_node, request_sql_approval, run_sql) ───

        generated_sql (str):
            Raw SQL string produced by the LLM using RDS PostgreSQL schema context.
            Validated by sqlglot AST before being surfaced to the operator for
            Human-in-the-Loop approval.

        sql_explanation (str):
            Plain-English explanation of what the generated SQL does, returned
            alongside generated_sql in the pending_sql approval block so operators
            can review intent before approving execution.

        sql_generation_cost_usd (float):
            Estimated OpenAI token cost (USD) for the SQL generation LLM call.
            Contributed to the overall cost_saved_usd telemetry on cache hits.

        sql_approved (bool):
            Set to True by the LangGraph resume path after the operator calls
            POST /query/sql/execute. The run_sql node checks this before executing
            against RDS PostgreSQL.

        sql_rows (list[dict]):
            Raw result rows returned from RDS PostgreSQL after approved SQL
            execution. Each dict maps column name → value. Consumed by run_hybrid
            in the hybrid branch or passed directly to finalize in the sql branch.

        sql_cache_hit (bool):
            True if generated_sql was served from the 'sql_gen' Upstash Redis
            cache tier rather than a live LLM call, or if sql_rows was served
            from the 'sql_result' cache tier.

    ── RAG PIPELINE — RETRIEVAL (set by run_rag / retrieve_rag_for_hybrid) ──────

        hypotheses (list[str]):
            Hypothetical answer strings generated by the HyDE node. Used as
            surrogate query vectors to improve Qdrant semantic retrieval on
            vague or abstract questions.

        retrieved_chunks (Annotated[list[RetrievedChunk], add]):
            Document chunks returned from Qdrant Cloud vector search. The `add`
            reducer merges chunks appended by multiple retrieval passes (e.g.
            dense + sparse in hybrid search mode) rather than overwriting them.

        reranked_chunks (list[RetrievedChunk]):
            Subset of retrieved_chunks reordered by a cross-encoder reranker.
            Populated only when enable_rerank=True is set in flags. Replaces
            retrieved_chunks as the context source for generation.

        spotlighted_context (str):
            Final formatted string passed to the LLM prompt, where each chunk
            is wrapped in explicit document boundaries (spotlighting). This is
            guardrail layer 8 — treating retrieved content as untrusted context
            to prevent prompt injection from document corpus.

        crag_evaluation (CRAGEvaluation):
            Structured grading result from the CRAG node assessing whether
            retrieved chunks are sufficient to answer the question. Triggers
            corrective behavior (re-retrieval or web fallback) when quality
            is below threshold. Populated only when enable_crag=True.

        web_results (list[RetrievedChunk]):
            Fallback web search results fetched via Tavily when CRAG determines
            Qdrant retrieval quality is insufficient. Merged with retrieved_chunks
            before generation.

    ── RAG PIPELINE — GENERATION (set by run_rag / run_hybrid) ─────────────────

        rag_cache_hit (bool):
            True if the full RAG answer was served from the 'rag_answer' Upstash
            Redis cache tier, bypassing Qdrant retrieval and LLM generation entirely.

        raw_answer (str):
            Unvalidated LLM generation output before output guardrail checks
            (layer 9) run in the finalize node.

        rag_answer (str):
            Validated RAG answer after output guardrail checks pass. This is the
            field the finalize node promotes to final_answer in the rag branch.

        rag_question (str):
            The question actually sent to the LLM for generation. May differ from
            the original question if Self-Reflective RAG rewrote it via refined_question.

        rag_sources (list[str]):
            Source document identifiers (chunk IDs or S3 keys) cited in the RAG
            answer. Surfaced as the 'sources' field in the API response.

        rag_confidence (float):
            Confidence score (0.0–1.0) for the RAG answer, derived from reranker
            scores or retrieval similarity metrics. Surfaced in response metadata.

        rag_metadata (dict):
            Retrieval telemetry dict containing fields such as retrieval_mode,
            chunk_count, rerank_applied, hyde_used, crag_triggered, and
            cache_tier_hit for observability and RAGAS evaluation logging.

    ── SELF-REFLECTIVE RAG (set by reflection node) ─────────────────────────────

        reflection (ReflectionResult):
            Structured output from the SRAG reflection node assessing whether the
            raw_answer adequately addresses the question. Contains a quality verdict
            and optional reasoning. Populated only when enable_self_reflective=True.

        reflection_iterations (int):
            Number of reflection-and-regeneration cycles completed. Capped to
            prevent infinite loops. Typically 0 (no reflection) or 1–2 iterations.

        refined_question (str):
            Rewritten question produced by the SRAG node when reflection determines
            the original phrasing caused poor retrieval. Replaces question for the
            next retrieval pass and is stored in rag_question before generation.

    ── FINALIZED OUTPUT (set by finalize node) ──────────────────────────────────

        final_answer (str):
            The validated, guardrail-checked answer returned to the API layer.
            Promoted from rag_answer (RAG branch), sql_rows formatted output
            (SQL branch), or the merged SQL + RAG narrative (hybrid branch).

        sources (list[str]):
            Deduplicated list of source references included in final_answer.
            Drawn from rag_sources (RAG/hybrid) or the executed SQL query string
            (SQL branch) for response transparency.

        confidence (float):
            Final confidence score attached to the API response. Drawn from
            rag_confidence or set to a fixed value for SQL-only answers.

    ── OBSERVABILITY & CACHE TELEMETRY (set across nodes, read by finalize) ─────

        chunk_previews (list[dict]):
            Truncated chunk text previews included in the API response metadata
            for debugging retrieval quality without exposing full chunk content.

        cache_hits (dict[str, bool]):
            Per-tier cache hit map across all five Upstash Redis tiers:
            {'rag_answer': bool, 'sql_gen': bool, 'sql_result': bool,
             'approved_answer': bool, 'embedding': bool}.

        cost_saved_usd (float):
            Estimated total cost avoided (USD) across all cache hits in this
            request, combining llm_cost_saved and infra_cost_saved telemetry.
            Surfaced in the API response for operator cost visibility.

        cache_hit (bool):
            Top-level boolean True if any cache tier was hit during this request.
            Used by the API response layer to set the cache_hit field without
            inspecting the full cache_hits dict.

        metadata (dict):
            Catch-all observability dict for fields that don't have a dedicated
            top-level slot — e.g. latency breakdowns, node execution order,
            LangGraph thread_id, and ECS task metadata for CloudWatch logging.
    """
  
    question: str
    user_id: str
    flags: dict

    intent: str
    generated_sql: str
    sql_explanation: str
    sql_generation_cost_usd: float
    sql_approved: bool
    sql_rows: list[dict]
    sql_cache_hit: bool

    hypotheses: list[str]

    retrieved_chunks: Annotated[list[RetrievedChunk], add]
    reranked_chunks: list[RetrievedChunk]
    spotlighted_context: str

    crag_evaluation: CRAGEvaluation
    web_results: list[RetrievedChunk]

    rag_cache_hit: bool
    raw_answer: str
    rag_answer: str
    rag_question: str
    rag_sources: list[str]
    rag_confidence: float
    rag_metadata: dict

    reflection: ReflectionResult
    reflection_iterations: int
    refined_question: str

    final_answer: str
    sources: list[str]
    confidence: float

    chunk_previews: list[dict]
    cache_hits: dict[str, bool]
    cost_saved_usd: float
    cache_hit: bool
    metadata: dict
